# OpenMerc MENU2: console scripts that hover the pointer over the tab bar, rows and buttons of the
# settings pages (om_menukey none x y) and capture each state; positions are 640x480 canvas units
import sys
W, H = int(sys.argv[1]), int(sys.argv[2])
fit = min(W / 640, H / 480)
f = int(fit) if fit >= 2 else fit
ox, oy = (W / f - 640) / 2, (H / f - 480) / 2
pts = [('tab1', 52, 20), ('tab2', 132, 20), ('tab3', 210, 20), ('row1', 250, 131), ('row5', 250, 188),
       ('help', 345, 354), ('back', 377, 354), ('btn', 560, 330)]
out = ['// generated by gen_hover.py %dx%d' % (W, H)]
t = 300
for page in ('video', 'audio', 'keys', 'scale', 'misc', 'options'):
    out.append('om_after %d "menuoff;menu %s"' % (t, page)); t += 40
    for name, x, y in pts:
        out.append('om_after %d "om_menukey none %d %d"' % (t, ox + x, oy + y)); t += 8
        out.append('om_after %d "om_menushot h_%s_%s"' % (t, page, name)); t += 4
out.append('om_after %d "quit"' % (t + 10))
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
