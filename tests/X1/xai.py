# OpenMerc X1 - enemy behaviour session, the same real-time script in mode A and mode B, then a per-phase census
# of what the other characters did, read from the sound debug log (s_om_debug 4: every sound start with its entity).
#   xai.py --make <intro seconds> <out.cfg> [--spawn m_kos_mgrunt1] [--hold S] [--burst N]   session script
#                                       (sound on; --burst: N screenshots 0.1 s apart after the walk)
#   xai.py <run dir> [<run dir> ...]                                            census, one block per run
# Phases: natural (stand still at the start), rear (gimme puts a character in front of the player, facing away),
# noise (one shot, upwards), walk (a few steps, then stand), killall. Timing is real time (om_delay): "wait" counts
# frames and the hidden window runs uncapped, so frame-counted scripts end inside the opening cinematic, where
# movement is frozen.
# A shot at the player is heard as a crack on the player (entity 1); a near miss as a flyby on the shooter.
# Implements: black-box test harness (no game code)
import re
import sys
from collections import Counter
from pathlib import Path

MARK = re.compile(r"^OMTEST (.+?)\s*$")
SND = re.compile(r"^OMsnd: \[p=\d+ cl=\d+\] start (\S+) ent (\d+) ")
POS = re.compile(r"^position: (-?\d+) (-?\d+) (-?\d+)")
KILLED = re.compile(r"^killed (\d+) monsters")
COLS = ("shot_at_player", "flyby", "impact", "reload", "voice", "char_hit", "char_death", "player_hurt")


def timeline(intro, spawn, hold, burst=0):
    t = [(3, "echo OMTEST intro")]
    for _ in range(max(1, int(intro / 2.5))):
        t += [(2.3, "+use"), (0.2, "-use")]
    t += [(3, "echo OMTEST natural;heretic;viewpos;omshot n0")]
    for i in range(1, int(hold / 5) + 1):
        t += [(5, "viewpos;omshot n%d" % i)]
    t += [(0.5, "echo OMTEST rear;gimme %s" % spawn)]
    for i in range(0, 6):
        t += [(1.5, "viewpos;omshot r%d" % i)]
    t += [(0.5, "echo OMTEST noise;+lookup"), (0.5, "-lookup;+attack"), (0.3, "-attack;centerview")]
    for i in range(0, 10):
        t += [(1.5, "viewpos;omshot z%d" % i)]
    t += [(0.5, "echo OMTEST walk;+forward"), (2.5, "-forward;viewpos;omshot k0")]
    for i in range(1, 4):
        t += [(4, "viewpos;omshot k%d" % i)]
    if burst:
        # screenshots every 0.1 s while the characters fire (muzzle flashes, impact sparks)
        t += [(0.5, "echo OMTEST burst")]
        for i in range(burst):
            t += [(0.1, "omshot b%02d" % i)]
    t += [(0.5, "echo OMTEST killall;killallmonsters"), (2, "omshot x0"), (1, "echo OMTEST quit"), (0, "quit")]
    return t


def make_cfg(intro, spawn, hold, burst=0):
    steps = timeline(intro, spawn, hold, burst)
    out = ["// generated by tests/X1/xai.py --make (enemy behaviour session, black-box harness)"]
    for i, (_, cmd) in enumerate(steps):
        dt = steps[i + 1][0] if i + 1 < len(steps) else 0
        nxt = ("om_delay %.2f om_a%d" % (dt, i + 1)) if i + 1 < len(steps) else ""
        if dt == 0 and nxt:
            nxt = "om_a%d" % (i + 1)
        out.append('alias om_a%d "%s"' % (i, cmd + (";" + nxt if nxt else "")))
    out.append("om_delay %.2f om_a0" % steps[0][0])
    return out


def kind(name, ent):
    """sound start -> census class (None = not counted)"""
    base = name.rsplit("/", 1)[-1]
    if ent == 1:
        if "/crack/" in name:
            return "shot_at_player"
        if "pain" in name:
            return "player_hurt"
        return None
    if "/flyby/" in name:
        return "flyby"
    if name.startswith("weapons/") and ("reload" in base or "cock" in base):
        return "reload"
    if name.startswith("enemy/dth/") and base.startswith("hit"):
        return "char_hit"
    if name.startswith("enemy/dth/"):
        return "char_death"
    if name.startswith("enemy/"):
        return "voice"
    if name.startswith("impact/surfs/") or "/rics/" in name:
        return "impact"
    return None


def census(d):
    d = Path(d)
    log = d / "client.log"
    if not log.exists():
        return d.name, None
    phase, rows, order = "start", {}, []
    for raw in log.read_text(encoding="cp1251", errors="replace").splitlines():
        m = MARK.match(raw)
        if m:
            phase = m.group(1)
            if phase not in rows:
                rows[phase] = {"c": Counter(), "shooters": Counter(), "pos": [], "voices": Counter()}
                order.append(phase)
            continue
        r = rows.get(phase)
        if r is None:
            continue
        m = SND.match(raw)
        if m:
            name, ent = m.group(1), int(m.group(2))
            k = kind(name, ent)
            if k:
                r["c"][k] += 1
                if k == "flyby":
                    r["shooters"][ent] += 1
                if k == "voice":
                    r["voices"][re.sub(r"\d+\.wav$", "N", name)] += 1
            continue
        m = POS.match(raw)
        if m:
            r["pos"].append(tuple(int(v) for v in m.groups()))
            continue
        m = KILLED.match(raw)
        if m:
            r["c"]["killed"] = int(m.group(1))
    return d.name, [(p, rows[p]) for p in order]


def main(argv):
    if argv[1] == "--make":
        spawn = argv[argv.index("--spawn") + 1] if "--spawn" in argv else "m_kos_mgrunt1"
        hold = float(argv[argv.index("--hold") + 1]) if "--hold" in argv else 25
        burst = int(argv[argv.index("--burst") + 1]) if "--burst" in argv else 0
        Path(argv[3]).write_text("\n".join(make_cfg(float(argv[2]), spawn, hold, burst)) + "\n", encoding="ascii")
        return
    print("phase    " + " ".join("%6s" % c[:6] for c in COLS) + "  flyby by entity | position first -> last")
    for a in argv[1:]:
        name, rows = census(a)
        print("== %s" % name)
        if rows is None:
            print("   no client.log")
            continue
        for p, r in rows:
            if p in ("intro", "quit"):
                continue
            c = r["c"]
            pos = "%s -> %s" % (r["pos"][0], r["pos"][-1]) if r["pos"] else "-"
            sh = " ".join("%d:%d" % kv for kv in sorted(r["shooters"].items()))
            print("%-8s " % p + " ".join("%6d" % c[k] for k in COLS) + "  %s | %s%s" % (
                sh or "-", pos, ("  killed %d" % c["killed"]) if "killed" in c else ""))
            if r["voices"]:
                print("         voices: " + ", ".join("%s x%d" % kv for kv in r["voices"].most_common(5)))


if __name__ == "__main__":
    main(sys.argv)
