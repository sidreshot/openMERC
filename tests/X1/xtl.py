# OpenMerc X1 - real-time session script from a timeline file (black-box test harness, no game code).
#   xtl.py <timeline.txt> <out.cfg>
# Timeline lines: "<seconds> <console commands>", the seconds are the wait BEFORE the commands (real time,
# om_delay). Blank lines and lines starting with # are skipped. Repetition:
#   repeat N <seconds> <commands with {i} (0..N-1) and {i2} (two digits)>
#   intro N        N seconds of +use / -use pulses (skips opening cinematics and dialogue)
# The last command should be "quit".
import sys
from pathlib import Path


def parse(text):
    steps = []
    for raw in text.splitlines():
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        w = s.split(None, 1)
        if w[0] == "intro":
            for _ in range(max(1, int(float(w[1]) / 2.5))):
                steps += [(2.3, "+use"), (0.2, "-use")]
            continue
        if w[0] == "repeat":
            n, rest = w[1].split(None, 1)
            dt, cmd = rest.split(None, 1)
            for i in range(int(n)):
                steps.append((float(dt), cmd.replace("{i2}", "%02d" % i).replace("{i}", str(i))))
            continue
        steps.append((float(w[0]), w[1] if len(w) > 1 else ""))
    return steps


def make_cfg(steps):
    out = ["// generated by tests/X1/xtl.py (black-box harness)"]
    for i, (_, cmd) in enumerate(steps):
        if i + 1 < len(steps):
            dt = steps[i + 1][0]
            nxt = ("om_delay %.2f om_a%d" % (dt, i + 1)) if dt > 0 else "om_a%d" % (i + 1)
            cmd = (cmd + ";" + nxt) if cmd else nxt
        out.append('alias om_a%d "%s"' % (i, cmd))
    out.append("om_delay %.2f om_a0" % max(steps[0][0], 0.1))
    return out


if __name__ == "__main__":
    Path(sys.argv[2]).write_text("\n".join(make_cfg(parse(Path(sys.argv[1]).read_text()))) + "\n", encoding="ascii")
