# Implements: SPEC-801 black-box checks (test harness, no game code)
# Writes the console scripts that open every top-level menu page and capture it:
#   menus_oracle.cfg  - original SoF.exe (capture shim: "echo OMSHOT <name>")
#   menus_om.cfg      - OpenMerc (om_menushot <name>)
# usage: python gen_scripts.py <outdir> [wait-frames]
import os
import sys

MENUS = [
    "disclaimer", "main", "quit", "game", "load", "save", "video", "audio", "keys", "misc", "scale",
    "language", "credits", "stats", "start", "join", "player", "options", "chat", "loading",
    "disconnect", "gfxinfo", "defaults", "bots", "dmflags", "advjoin", "joystick", "motd",
]


def script(kind, wait):
    lines = [
        "// generated by gen_scripts.py",
        'alias w10 "wait;wait;wait;wait;wait;wait;wait;wait;wait;wait"',
        'alias w100 "w10;w10;w10;w10;w10;w10;w10;w10;w10;w10"',
        "set menu_dc_reason \"Test disconnect reason\"",
        "w100",
    ]
    for m in MENUS:
        lines.append("menuoff")
        lines.append("menu %s" % m)
        lines += ["w100"] * wait
        lines.append("echo OMSHOT %s" % m if kind == "oracle" else "om_menushot %s" % m)
        lines += ["w100"]
    lines.append("menuoff")
    lines.append("w100")
    lines.append("quit")
    return "\r\n".join(lines) + "\r\n"


def main():
    out = sys.argv[1]
    wait = int(sys.argv[2]) if len(sys.argv) > 2 else 3
    os.makedirs(out, exist_ok=True)
    for kind in ("oracle", "om"):
        with open(os.path.join(out, "menus_%s.cfg" % kind), "w", newline="") as f:
            f.write(script(kind, wait))
    # OpenMerc: frame-driven tour (the console's "wait" is not tied to drawn frames there)
    with open(os.path.join(out, "menus_om_tour.cfg"), "w", newline="") as f:
        f.write("// generated by gen_scripts.py\r\n")
        f.write("set menu_dc_reason \"Test disconnect reason\"\r\n")
        f.write("om_menutour 60 quit %s\r\n" % " ".join(MENUS))


if __name__ == "__main__":
    main()
