def view(name, eye, moments=2):
    """A paused shot at the eye, then (moments - 1) more after 10 unpaused frames each."""
    out = ['pause', 'set om_capview "%s 1"' % eye, 'w10', 'echo OMSHOT %s_0' % name, 'w40']
    for k in range(1, moments):
        out += ['pause', 'w10', 'pause', 'w10', 'echo OMSHOT %s_%d' % (name, k), 'w40']
    out += ['set om_capview ""', 'pause', 'w10']
    return out


def views(table, loadwait=3):
    out = []
    cur = None
    for name, m, eye in table:
        if m != cur:
            out += ['map %s' % m] + ['w100'] * loadwait
            cur = m
        out += view(name, eye)
    return out


def spawns(prefix, maps, sets, loadwait=3, reload=False):
    """Paused spawn views of maps under each cvar setting (reload: load the map again per setting)."""
    out = []
    for m in maps:
        if not reload:
            out += ['map %s' % m] + ['w100'] * loadwait + ['pause', 'w10']
        for tag, cmds in sets:
            if reload:
                out += cmds + ['map %s' % m] + ['w100'] * loadwait + ['pause', 'w10']
            else:
                out += cmds + ['w10']
            out += ['echo OMSHOT %s_%s_%s' % (prefix, m, tag), 'w40']
            if reload:
                out += ['pause', 'w10']
        if not reload:
            out += ['pause', 'w10']
    return out


def write(path, lines):
    with open(path, 'w', newline='\n') as f:
        # archived cvars a run may change on the command line go back to the test copy's values
        tail = ['set gl_fogmode 0', 'set gl_modulate 1', 'set gl_monolightmap 0', 'set r_fullbright 0', 'quit']
        f.write('\n'.join(HEAD + lines + tail) + '\n')


def main():
    d = sys.argv[1]
    os.makedirs(d, exist_ok=True)
    write(os.path.join(d, 'flow.cfg'), views(FLOW))
    write(os.path.join(d, 'liquid.cfg'), views(LIQUID))
    write(os.path.join(d, 'detail.cfg'), views(DETAIL))
    fog = [('m0', ['set gl_fogmode 0']), ('m1', ['set gl_fogmode 1']), ('m2', ['set gl_fogmode 2'])]
    write(os.path.join(d, 'fogmode.cfg'), spawns('fm', ['irq3b', 'ger1', 'tsr1', 'nyc2'], fog) + ['set gl_fogmode 0'])
    mono = [(t, ['set gl_monolightmap %s' % v]) for t, v in
            (('0', '0'), ('L', 'L'), ('I', 'I'), ('C', 'C'), ('A', 'A'), ('x', 'x'), ('l', 'l'))]
    # flushmap 1: the same map is loaded again, so its lightmaps are rebuilt with the new mode (SPEC-002 0x10)
    write(os.path.join(d, 'mono.cfg'), ['set flushmap 1'] + spawns('ml', ['ger1'], mono, reload=True) +
          ['set gl_monolightmap 0', 'set flushmap 0'])


if __name__ == '__main__':
    main()
