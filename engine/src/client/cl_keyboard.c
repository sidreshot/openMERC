/* OpenMerc: Unicode code point -> font byte. SoF fonts are drawn byte for
   byte (Latin-1 in the Western releases, CP1251 in the Russian one), so a
   Cyrillic letter becomes its CP1251 byte and U+00A0..U+00FF its Latin-1
   byte; anything else has no glyph and is dropped (0). */
static const unsigned short cp1251_high[64] = {
	0x0402, 0x0403, 0x201A, 0x0453, 0x201E, 0x2026, 0x2020, 0x2021,
	0x20AC, 0x2030, 0x0409, 0x2039, 0x040A, 0x040C, 0x040B, 0x040F,
	0x0452, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014,
	0x0000, 0x2122, 0x0459, 0x203A, 0x045A, 0x045C, 0x045B, 0x045F,
	0x00A0, 0x040E, 0x045E, 0x0408, 0x00A4, 0x0490, 0x00A6, 0x00A7,
	0x0401, 0x00A9, 0x0404, 0x00AB, 0x00AC, 0x00AD, 0x00AE, 0x0407,
	0x00B0, 0x00B1, 0x0406, 0x0456, 0x0491, 0x00B5, 0x00B6, 0x00B7,
	0x0451, 0x2116, 0x0454, 0x00BB, 0x0458, 0x0405, 0x0455, 0x0457
};

int
Key_UnicodeToFont(unsigned cp)
{
	int i;

	if ((cp >= 32) && (cp < 127))
	{
		return (int)cp;
	}

	/* the SoF fonts have no glyph for Yo (CP1251 A8/B8 draw blank in the
	   Russian conchars): typed as Ye, the usual Russian fallback */
	if (cp == 0x0401)
	{
		return 0xC5;
	}

	if (cp == 0x0451)
	{
		return 0xE5;
	}

	if ((cp >= 0x0410) && (cp <= 0x044F))
	{
		return (int)(cp - 0x0410 + 0xC0);
	}

	if ((cp >= 0x0400) && (cp <= 0x04FF))
	{
		for (i = 0; i < 64; i++)
		{
			if (cp1251_high[i] == cp)
			{
				return 0x80 + i;
			}
		}

		return 0;
	}

	if ((cp >= 0xA0) && (cp <= 0xFF))
	{
		return (int)cp;
	}

	return 0;
}

/* first code point of a UTF-8 string, 0 when it is malformed */
static unsigned
Key_Utf8First(const char *s)
{
	const unsigned char *u = (const unsigned char *)s;
	unsigned cp;
	int n, i;

	if (!u || !u[0])
	{
		return 0;
	}

	if (u[0] < 0x80)
	{
		return u[0];
	}
	else if ((u[0] & 0xE0) == 0xC0)
	{
		cp = u[0] & 0x1F;
		n = 1;
	}
	else if ((u[0] & 0xF0) == 0xE0)
	{
		cp = u[0] & 0x0F;
		n = 2;
	}
	else if ((u[0] & 0xF8) == 0xF0)
	{
		cp = u[0] & 0x07;
		n = 3;
	}
	else
	{
		return 0;
	}

	for (i = 1; i <= n; i++)
	{
		if ((u[i] & 0xC0) != 0x80)
		{
			return 0;
		}

		cp = (cp << 6) | (u[i] & 0x3F);
	}

	return cp;
}

/* OpenMerc: the operating system's text for the key just pressed (SDL text
   input, UTF-8). It never adds a character: it only replaces the one the SoF
   layout table typed for that press, so bindings, the console key and line
   lengths are unchanged. With sp_language 0 (the US table) the OS layout
   wins for every character, so a Russian or German Windows layout types
   what its keys show; with the German/French/Spanish tables (1..3) only
   characters outside ASCII replace the table's, as SoF emulates those
   layouts itself. */
void
Key_TextInputCodepoint(unsigned cp)
{
	int b = Key_UnicodeToFont(cp);
	int pending = text_pending;

	text_pending = 0;

	if (!pending || (b < 32))
	{
		return;
	}

	if (pending == 3)
	{
		char txt[2];

		txt[0] = (char)b;
		txt[1] = 0;

		if (cls.key_dest == key_console)
		{
			Key_AppendLine(txt);
		}
		else if ((cls.key_dest == key_message) && (chat_bufferlen < SOF_CMDLINE_CHARS))
		{
			chat_buffer[chat_bufferlen++] = txt[0];
			chat_buffer[chat_bufferlen] = 0;
			chat_cursorpos = chat_bufferlen;
		}

		text_pending = 3; /* a VK_PACKET press may carry several characters */
		return;
	}

	if ((b < 0x80) && (Key_LayoutColumn() != 0))
	{
		return;
	}

	if ((pending == 1) && (cls.key_dest != key_menu) &&
		(text_pending_pos < (int)strlen(key_lines[edit_line])))
	{
		key_lines[edit_line][text_pending_pos] = (char)b;
	}
	else if ((pending == 2) && (cls.key_dest == key_message) &&
		(text_pending_pos < chat_bufferlen))
	{
		chat_buffer[text_pending_pos] = (char)b;
	}
}

void
Key_TextInput(const char *utf8)
{
	Key_TextInputCodepoint(Key_Utf8First(utf8));
}

/* length of the UTF-8 sequence that starts with byte c (1 for a stray byte) */
static int
Key_Utf8Len(unsigned char c)
{
	if ((c & 0xE0) == 0xC0)
	{
		return 2;
	}

	if ((c & 0xF0) == 0xE0)
	{
		return 3;
	}

	if ((c & 0xF8) == 0xF0)
	{
		return 4;
	}

	return 1;
}

/* in place: UTF-8 text (the clipboard) -> font bytes; characters without a
   glyph are dropped. Text that is not valid UTF-8 is kept byte for byte, so
   a CP1251 clipboard (old programs) still pastes. */
static void
Key_Utf8ToFont(char *s)
{
	unsigned char *r = (unsigned char *)s, *w = (unsigned char *)s;
	unsigned cp;
	int n, i;

	for (i = 0; r[i]; i += n)
	{
		n = Key_Utf8Len(r[i]);

		if (n > 1)
		{
			int k;

			for (k = 1; k < n; k++)
			{
				if ((r[i + k] & 0xC0) != 0x80)
				{
					return; /* not UTF-8: leave the text as it is */
				}
			}
		}
	}

	while (*r)
	{
		n = Key_Utf8Len(*r);
		cp = (n == 1) ? *r : Key_Utf8First((const char *)r);
		r += n;
		i = (cp < 32) ? (int)cp : Key_UnicodeToFont(cp);

		if (i)
		{
			*w++ = (unsigned char)i;
		}
	}

	*w = 0;
}

static qboolean
Key_DemoPlayback(void)
{
	return cl.attractloop || CL_Demo_Playing();
}

/* "the binding runs" (SPEC-312 4 rule 7) */
static void
Key_RunBinding(int key, unsigned time)
{
	char cmd[1024];
	const char *kb = keybindings[key];

	if (!kb || !kb[0])
	{
		return;
	}

	if (kb[0] == '+')
	{
		Com_sprintf(cmd, sizeof(cmd), "%s %i %u\n", kb, key, time);
		Cbuf_AddText(cmd);
		return;
	}

	Cbuf_AddText((char *)kb);
	Cbuf_AddText("\n");
	Q_strlcpy(pending_weapon_cmd, kb, sizeof(pending_weapon_cmd));
}

void
Key_EventEx(int key, qboolean down, qboolean extended, unsigned time)
{
	char cmd[1024];
	const char *kb;
	int flags;

	if ((key <= 0) || (key >= K_LAST))
	{
		return;
	}

	if (down)
	{
		text_pending = 0; /* OS text belongs to the press that typed it */
	}

	/* OpenMerc: Windows VK_PACKET carries a character, not a key (input
	   methods, the on-screen keyboard): its text is inserted, it is never
	   bound */
	if (key == 0xE7)
	{
		if (down && ((cls.key_dest == key_console) || (cls.key_dest == key_message)))
		{
			text_pending = 3;
		}

		return;
	}

	/* 1. keypad translation */
	if (!extended && keytable[key].keypad)
	{
		key = keytable[key].keypad;
	}

	/* 2. auto-repeat */
	if (down)
	{
		key_repeats[key]++;

		if ((key_repeats[key] > 1) && (cls.key_dest != key_menu) &&
			(key != K_BACKSPACE) && (key != K_PAUSE) && (key != K_PGUP) &&
			(key != K_KP_PGUP) && (key != K_PGDN) && (key != K_KP_PGDN))
		{
			return;
		}
	}
	else
	{
		key_repeats[key] = 0;
	}

	/* 3. the console key: the key that types a grave accent or a tilde.
	   OpenMerc: also over the menus (1.07f ignored it there) */
	if ((Key_Char(key, false) == 0x60) || (Key_Char(key, Key_ShiftDown()) == 0x7e))
	{
		if (down)
		{
			Con_ToggleConsole_f();
		}

		return;
	}

	/* 4. Escape, and every key during demo playback */
	if ((key == K_ESCAPE) || (Key_DemoPlayback() && (cls.key_dest != key_menu)))
	{
		if (!down)
		{
			return;
		}

		switch (cls.key_dest)
		{
			case key_message:
				Key_Message(K_ESCAPE);
				break;

			case key_menu:
				M_Keydown(K_ESCAPE);
				break;

			case key_game:
			case key_console:
			default:
				if ((cls.key_dest == key_game) && CL_CinematicFreezeActive())
				{
					CL_RequestCinematicSkip(); /* SPEC-312 section 11 */
				}
				else
				{
					Cbuf_AddText("menu main\n");
				}

				break;
		}

		return;
	}

	/* 5. held state and the "any key held" counter */
	keydown[key] = down;

	if (down)
	{
		if (key_repeats[key] == 1)
		{
			anykeydown++;
		}
	}
	else
	{
		anykeydown--;

		if (anykeydown < 0)
		{
			anykeydown = 0;
		}
	}

	/* 6. release: button commands get their '-' command */
	if (!down)
	{
		kb = keybindings[key];

		if (kb && (kb[0] == '+'))
		{
			Com_sprintf(cmd, sizeof(cmd), "-%s %i %u\n", kb + 1, key, time);
			Cbuf_AddText(cmd);
		}

		return;
	}

	/* 7. press: routing by key focus */
	flags = keytable[key].flags;

	switch (cls.key_dest)
	{
		case key_menu:
			if (flags & KEYF_MENU)
			{
				Key_RunBinding(key, time);
			}
			else
			{
				M_Keydown(key);
			}

			break;

		case key_console:
			if (flags & KEYF_TEXT)
			{
				Key_Console(key);
			}
			else
			{
				Key_RunBinding(key, time);
			}

			break;

		case key_message:
			Key_Message(key);
			break;

		case key_game:
		default:
			if ((cls.state == ca_active) || !(flags & KEYF_TEXT))
			{
				Key_RunBinding(key, time);
			}
			else
			{
				Key_Console(key);
			}

			break;
	}
}

/* events from code that has no extended-key information (mouse, wheel,
   joystick, virtual keys): never translated to keypad keys */
void
Key_Event(int key, qboolean down, qboolean special)
{
	(void)special;
	Key_EventEx(key, down, true, Sys_Milliseconds());
}

/*
 * SPEC-312 4.6: every held key (or key with a press count) gets a release
 * event with time 0; all held flags, counters and "any key" are cleared
 */
void
Key_ReleaseAll(void)
{
	char cmd[1024];
	int key;

	for (key = 0; key < K_LAST; key++)
	{
		if (keydown[key] || key_repeats[key])
		{
			const char *kb = keybindings[key];

			if (kb && (kb[0] == '+'))
			{
				Com_sprintf(cmd, sizeof(cmd), "-%s %i 0\n", kb + 1, key);
				Cbuf_AddText(cmd);
			}
		}

		key_repeats[key] = 0;
		keydown[key] = false;
	}

	anykeydown = 0;
}

/*
 * Marks all keys as "up" (no release commands)
 */
void
Key_MarkAllUp(void)
{
	int key;

	for (key = 0; key < K_LAST; key++)
	{
		key_repeats[key] = 0;
		keydown[key] = 0;
	}

	anykeydown = 0;
}
