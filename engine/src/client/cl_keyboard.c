static void
Key_HistoryPath(char *path, size_t size)
{
	if (is_portable)
	{
		#ifdef _WIN32
		Com_sprintf(path, size, "%sconsole_history.txt", Sys_GetPortableLogDir());
#else
		/* the user folder <binary dir>/openmerc/user when openMERC's folder is
		   there (docs/impl/INSTALL-LAYOUT.md), never the game folder */
		char dir[MAX_OSPATH];

		Com_sprintf(dir, sizeof(dir), "%sopenmerc", Sys_GetBinaryDir());
		if (Sys_IsDir(dir))
		{
			Com_sprintf(dir, sizeof(dir), "%sopenmerc/user", Sys_GetBinaryDir());
			Sys_Mkdir(dir);
			Com_sprintf(path, size, "%s/console_history.txt", dir);
		}
		else
		{
			Com_sprintf(path, size, "%sconsole_history.txt", Sys_GetBinaryDir());
		}
#endif
	}
	else
	{
		Com_sprintf(path, size, "%sconsole_history.txt", Sys_GetHomeDir());
	}
}

void
Key_WriteConsoleHistory()
{
	int i;
	char path[MAX_OSPATH];
	FILE *f;
	const char *lastWrittenLine = "";

	Key_HistoryPath(path, sizeof(path));
	f = Q_fopen(path, "w");

	if (f == NULL)
	{
		Com_Printf("Opening console history %s for writing failed!\n", path);
		return;
	}

	/* save the oldest lines first */
	for (i = 0; i < NUM_KEY_LINES; ++i)
	{
		int lineIdx = (edit_line + i) & (NUM_KEY_LINES - 1);
		const char *line = key_lines[lineIdx];

		if ((*line != '\0') && strcmp(lastWrittenLine, line) != 0)
		{
			fputs(line, f);
			fputc('\n', f);
			lastWrittenLine = line;
		}
	}

	fclose(f);
}

void
Key_ReadConsoleHistory()
{
	FILE *f;
	int i;
	char path[MAX_OSPATH];

	Key_HistoryPath(path, sizeof(path));
	f = Q_fopen(path, "r");

	if (f == NULL)
	{
		Com_DPrintf("Opening console history %s for reading failed!\n", path);
		return;
	}

	for (i = 0; i < NUM_KEY_LINES; i++)
	{
		int lastCharIdx;

		if (fgets(key_lines[i], MAXCMDLINE, f) == NULL)
		{
			edit_line = i;
			history_line = i;
			break;
		}

		lastCharIdx = (int)strlen(key_lines[i]) - 1;

		while ((lastCharIdx >= 0) && ((key_lines[i][lastCharIdx] == '\n') ||
				(key_lines[i][lastCharIdx] == '\r')))
		{
			key_lines[i][lastCharIdx] = '\0';
			--lastCharIdx;
		}

		key_lines[i][SOF_CMDLINE_CHARS] = 0;
	}

	Key_ClearTyping();
	fclose(f);
}

