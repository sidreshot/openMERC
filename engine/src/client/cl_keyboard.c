static char keynames_generated[256][8];

static void
Key_BuildTable(void)
{
	const keydef_t *d;
	int i, j;

	memset(keytable, 0, sizeof(keytable));

	for (d = keydefs; d->num >= 0; d++)
	{
		keyinfo_t *k = &keytable[d->num];

		k->name = d->name;
		memcpy(k->chars[0], d->un, 4);
		memcpy(k->chars[1], d->sh, 4);
		k->keypad = d->keypad;
		k->flags = d->flags;
	}

	for (i = 'A'; i <= 'Z'; i++)
	{
		keynames_generated[i][0] = (char)i;
		keynames_generated[i][1] = 0;
		keytable[i].name = keynames_generated[i];
		keytable[i].flags = KEYF_TEXT | KEYF_CLICK;

		for (j = 0; j < 4; j++)
		{
			keytable[i].chars[0][j] = (byte)(i + 32);
			keytable[i].chars[1][j] = (byte)i;
		}
	}

	for (i = 0; i < 12; i++)
	{
		Com_sprintf(keynames_generated[K_F1 + i], 8, "F%d", i + 1);
		keytable[K_F1 + i].name = keynames_generated[K_F1 + i];
		keytable[K_F1 + i].flags = KEYF_MENU;
	}

	for (i = 4; i <= 32; i++)
	{
		Com_sprintf(keynames_generated[K_AUX1 + i - 1], 8, "AUX%d", i);
		keytable[K_AUX1 + i - 1].name = keynames_generated[K_AUX1 + i - 1];
	}
}

/* SPEC-312 section 2: layout column = sp_language clamped to 0..3 */
static int
Key_LayoutColumn(void)
{
	int l;

	if (!sp_language)
	{
		sp_language = Cvar_Get("sp_language", "0", CVAR_ARCHIVE);
	}

	l = (int)sp_language->value;

	if ((l < 0) || (l > 3))
	{
		l = 0;
	}

	return l;
}

int
Key_ShiftDown(void)
{
	return keydown[K_LSHIFT] || keydown[K_RSHIFT];
}

int
Key_Char(int key, qboolean shifted)
{
	if ((key < 0) || (key >= K_LAST))
	{
		return 0;
	}

	return keytable[key].chars[shifted ? 1 : 0][Key_LayoutColumn()];
}

