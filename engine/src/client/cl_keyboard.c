void
Key_SetBinding(int keynum, char *binding)
{
	char *new;
	size_t l;

	if ((keynum < 0) || (keynum >= K_LAST))
	{
		return;
	}

	/* free old bindings */
	if (keybindings[keynum])
	{
		Z_Free(keybindings[keynum]);
		keybindings[keynum] = NULL;
	}

	/* allocate memory for new binding */
	l = strlen(binding);
	new = Z_Malloc((int)(l + 1));
	memcpy(new, binding, l + 1);
	keybindings[keynum] = new;
	key_bindings_changed = true;
}

/* bindings of menu-bound keys do not change while a menu has key focus */
static qboolean
Key_BindingLocked(int key)
{
	return (cls.key_dest == key_menu) && (keytable[key].flags & KEYF_MENU);
}

static void
Key_Unbind_f(void)
{
	int b;

	if (Cmd_Argc() != 2)
	{
		Com_Printf("unbind <key> : remove all commands from a key\n");
		return;
	}

	b = Key_StringToKeynum(Cmd_Argv(1));

	if (b == -1)
	{
		Com_Printf("\"%s\" isn't a valid key\n", Cmd_Argv(1));
		return;
	}

	if (Key_BindingLocked(b))
	{
		return;
	}

	Key_SetBinding(b, "");
}

static void
Key_Unbindall_f(void)
{
	int i;

	for (i = 0; i < K_LAST; i++)
	{
		if (keybindings[i] && !Key_BindingLocked(i))
		{
			Key_SetBinding(i, "");
		}
	}
}

static void
Key_Bind_f(void)
{
	int i, c, b;
	char cmd[1024];

	c = Cmd_Argc();

	if (c < 2)
	{
		Com_Printf("bind <key> [command] : attach a command to a key\n");
		return;
	}

	b = Key_StringToKeynum(Cmd_Argv(1));

	if (b == -1)
	{
		Com_Printf("\"%s\" isn't a valid key\n", Cmd_Argv(1));
		return;
	}

	if (c == 2)
	{
		if (keybindings[b])
		{
			Com_Printf("\"%s\" = \"%s\"\n", Cmd_Argv(1), keybindings[b]);
		}
		else
		{
			Com_Printf("\"%s\" is not bound\n", Cmd_Argv(1));
		}

		return;
	}

	if (Key_BindingLocked(b))
	{
		return;
	}

	/* copy the rest of the command line */
	cmd[0] = 0;

	for (i = 2; i < c; i++)
	{
		Q_strlcat(cmd, Cmd_Argv(i), sizeof(cmd));

		if (i != (c - 1))
		{
			Q_strlcat(cmd, " ", sizeof(cmd));
		}
	}

	Key_SetBinding(b, cmd);
}

