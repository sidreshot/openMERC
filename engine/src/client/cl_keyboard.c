/* The line without the leading '\' or '/' */
static const char *
Key_LineText(void)
{
	const char *s = key_lines[edit_line];

	if ((*s == '\\') || (*s == '/'))
	{
		s++;
	}

	return s;
}

static void
Key_SetLine(const char *text)
{
	Q_strlcpy(key_lines[edit_line], text, SOF_CMDLINE_CHARS + 1);
	key_linepos = (int)strlen(key_lines[edit_line]);
}

/* true when 'name' is a visible cvar */
static qboolean
Key_IsCvar(const char *name)
{
	cvar_t *v;

	for (v = cvar_vars; v; v = v->next)
	{
		if (!(v->flags & CVAR_HIDDEN) && !strcmp(v->name, name))
		{
			return true;
		}
	}

	return false;
}

/* Next cvar candidate after 'last' (NULL: the first one): exact match
   first, then prefix matches in list order. The engine does not let the
   client walk its command and alias lists yet, so commands are offered
   only as the first match (see docs/impl/I6h.md, needs from I1a). */
static const char *
Key_NextCvarCompletion(const char *prefix, const char *last)
{
	cvar_t *v;
	size_t len = strlen(prefix);
	qboolean passed = (last == NULL);
	int pass;

	if (!len)
	{
		return NULL;
	}

	for (pass = 0; pass < 2; pass++)
	{
		for (v = cvar_vars; v; v = v->next)
		{
			if (v->flags & CVAR_HIDDEN)
			{
				continue;
			}

			if ((pass == 0) ? (strcmp(v->name, prefix) != 0) :
					(strncmp(v->name, prefix, len) || !strcmp(v->name, prefix)))
			{
				continue;
			}

			if (passed)
			{
				return v->name;
			}

			if (!strcmp(v->name, last))
			{
				passed = true;
			}
		}
	}

	return NULL;
}

static void
Key_CompleteCommand(void)
{
	const char *match = NULL;

	if (!completion_active)
	{
		Q_strlcpy(completion_prefix, Key_LineText(), sizeof(completion_prefix));

		if (!completion_prefix[0])
		{
			return;
		}

		if (Cmd_Exists(completion_prefix))
		{
			match = completion_prefix;
		}
		else
		{
			/* the engine completion returns a common prefix when several
			   names match; only a full name counts */
			match = Cmd_CompleteCommand(completion_prefix);

			if (match && !Cmd_Exists(match) && !Key_IsCvar(match))
			{
				match = NULL;
			}
		}

		if (!match || Key_IsCvar(match))
		{
			match = Key_NextCvarCompletion(completion_prefix, NULL);
		}
	}
	else
	{
		match = Key_NextCvarCompletion(completion_prefix,
				Key_IsCvar(completion_last) ? completion_last : NULL);

		if (!match)
		{
			match = Key_NextCvarCompletion(completion_prefix, NULL); /* wrap */
		}
	}

	if (!match)
	{
		return;
	}

	completion_active = true;
	Q_strlcpy(completion_last, match, sizeof(completion_last));

	key_lines[edit_line][0] = '/';
	Q_strlcpy(key_lines[edit_line] + 1, match, SOF_CMDLINE_CHARS);
	Q_strlcat(key_lines[edit_line], " ", SOF_CMDLINE_CHARS + 1);
	key_linepos = (int)strlen(key_lines[edit_line]);
}

static void
Key_AppendLine(const char *text)
{
	size_t len = strlen(key_lines[edit_line]);

	while (*text && (len < SOF_CMDLINE_CHARS))
	{
		key_lines[edit_line][len++] = *text++;
	}

	key_lines[edit_line][len] = 0;
	key_linepos = (int)len;
}

static void
Key_Console(int key)
{
	char cliptext[MAXCMDLINE];
	char txt[2];
	int c, i;

	if (key != K_TAB)
	{
		completion_active = false;
	}

	/* paste: Shift + INS, or Ctrl + V */
	if ((Key_ShiftDown() && (keydown[K_INS] || keydown[K_KP_INS])) ||
		(Key_CtrlDown() && keydown['V']))
	{
		IN_GetClipboardText(cliptext, sizeof(cliptext));

		for (i = 0; cliptext[i]; i++)
		{
			if ((cliptext[i] == '\r') || (cliptext[i] == '\n') || (cliptext[i] == 8))
			{
				cliptext[i] = 0;
				break;
			}
		}

		Key_Utf8ToFont(cliptext);
		Key_AppendLine(cliptext);
		return;
	}

	if (Key_CtrlDown() && keydown['L'])
	{
		Cbuf_AddText("clear\n");
		return;
	}

	switch (key)
	{
		case K_ENTER:
		case K_KP_ENTER:
			Cbuf_AddText((char *)Key_LineText());
			Cbuf_AddText("\n");
			Com_Printf("]%s\n", key_lines[edit_line]);

			edit_line = (edit_line + 1) & (NUM_KEY_LINES - 1);
			history_line = edit_line;
			Key_ClearTyping();

			if (cls.state == ca_disconnected)
			{
				SCR_UpdateScreen(); /* the command may take some time */
			}

			return;

		case K_TAB:
			Key_CompleteCommand();
			return;

		case K_BACKSPACE:
		case K_LEFTARROW:
			i = (int)strlen(key_lines[edit_line]);

			if (i > 0)
			{
				key_lines[edit_line][i - 1] = 0;
			}

			key_linepos = (int)strlen(key_lines[edit_line]);
			return;

		case K_UPARROW:
			do
			{
				history_line = (history_line - 1) & (NUM_KEY_LINES - 1);
			}
			while ((history_line != edit_line) && !key_lines[history_line][0]);

			if (history_line == edit_line)
			{
				history_line = (edit_line + 1) & (NUM_KEY_LINES - 1);
			}

			Key_SetLine(key_lines[history_line]);
			return;

		case K_DOWNARROW:
			if (history_line == edit_line)
			{
				return;
			}

			do
			{
				history_line = (history_line + 1) & (NUM_KEY_LINES - 1);
			}
			while ((history_line != edit_line) && !key_lines[history_line][0]);

			if (history_line == edit_line)
			{
				Key_ClearTyping();
			}
			else
			{
				Key_SetLine(key_lines[history_line]);
			}

			return;

		case K_PGUP:
			con.display -= 2;
			return;

		case K_PGDN:
			con.display += 2;

			if (con.display > con.current)
			{
				con.display = con.current;
			}

			return;

		case K_HOME:
			con.display = con.current - con.totallines + 10;
			return;

		case K_END:
			con.display = con.current;
			return;

		default:
			break;
	}

	c = Key_Char(key, Key_ShiftDown());

	if (c < 32)
	{
		return;
	}

	txt[0] = (char)c;
	txt[1] = 0;
	i = (int)strlen(key_lines[edit_line]);
	Key_AppendLine(txt);

	if (key_linepos > i) /* not when the line is full */
	{
		text_pending = 1;
		text_pending_pos = key_linepos - 1;
	}
}

/* ---------------------------------------------------------------------
 * chat line (SPEC-312 5.3)
 * --------------------------------------------------------------------- */

qboolean chat_team;
char chat_buffer[MAXCMDLINE];
int chat_bufferlen = 0;
int chat_cursorpos = 0;

static void
Key_ClearChat(void)
{
	chat_bufferlen = 0;
	chat_cursorpos = 0;
	chat_buffer[0] = 0;
}

static void
Key_Message(int key)
{
	int c;

	if ((key == K_ENTER) || (key == K_KP_ENTER))
	{
		Cbuf_AddText(chat_team ? "say_team \"" : "say \"");
		Cbuf_AddText(chat_buffer);
		Cbuf_AddText("\"\n");

		cls.key_dest = key_game;
		Key_ClearChat();
		return;
	}

	if (key == K_ESCAPE)
	{
		cls.key_dest = key_game;
		Key_ClearChat();
		return;
	}

	if (key == K_BACKSPACE)
	{
		if (chat_bufferlen)
		{
			chat_buffer[--chat_bufferlen] = 0;
			chat_cursorpos = chat_bufferlen;
		}

		return;
	}

	c = Key_Char(key, Key_ShiftDown());

	if ((c == 0) || (c == '\n') || (c == '\r'))
	{
		return;
	}

	if (chat_bufferlen >= SOF_CMDLINE_CHARS)
	{
		return;
	}

	chat_buffer[chat_bufferlen++] = (char)c;
	chat_buffer[chat_bufferlen] = 0;
	chat_cursorpos = chat_bufferlen;
	text_pending = 2;
	text_pending_pos = chat_bufferlen - 1;
}

/* ---------------------------------------------------------------------
 * key names and bindings (SPEC-312 section 6)
 * --------------------------------------------------------------------- */

int
Key_StringToKeynum(const char *str)
{
	int i;

	if (!str || !str[0])
	{
		return -1;
	}

	for (i = 0; i < K_LAST; i++)
	{
		if (keytable[i].name && !Q_stricmp(str, keytable[i].name))
		{
			return i;
		}
	}

	return -1;
}

