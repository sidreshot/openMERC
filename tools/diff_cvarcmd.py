# Implements: SPEC-302 (cvarlist output, complete cvar and command lists)
"""Compares the cvarlist / cmdlist output of two console logs (the original
1.07f as a black box, and OpenMerc) and writes a Markdown report.

Each log must contain the output of `cvarlist` (lines of 13 flag columns, a
space, the name, a space, the quoted value; last line "<n> cvars") followed
by `cmdlist` (one name per line, last line "<n> commands").

Missing names are classified with SPEC-302's "Registered by" column and the
owning OpenMerc package (docs/IMPLEMENTATION.md).

usage: diff_cvarcmd.py <oracle.log> <openmerc.log> <SPEC-302.md> <out.md>
"""
import re
import sys

FLAGCOLS = '*US-LIPNPWEAM'


def parse_log(path):
    cvars, cmds = {}, []
    order = []
    state = None
    text = open(path, encoding='latin-1').read().replace('\r\n', '\n').split('\n')
    for line in text:
        m = re.match(r'^(.{13}) (\S+) "(.*)"$', line)
        if m and state in (None, 'cvar'):
            state = 'cvar'
            cvars[m.group(2)] = (m.group(1), m.group(3))
            order.append(m.group(2))
            continue
        m = re.match(r'^(\d+) cvars$', line)
        if m and state == 'cvar':
            state = 'cmd'
            ncvars = int(m.group(1))
            continue
        if state == 'cmd':
            m = re.match(r'^(\d+) commands$', line)
            if m:
                ncmds = int(m.group(1))
                state = 'done'
                continue
            if line.strip() and not line.startswith(' '):
                cmds.append(line.strip())
    return cvars, cmds, ncvars, ncmds


def parse_spec(path):
    """name -> registered-by text for cvars and commands."""
    cv, cm = {}, {}
    section = None
    for line in open(path, encoding='utf-8'):
        if line.startswith('## Complete cvar list'):
            section = 'cvar'
        elif line.startswith('## Complete command list'):
            section = 'cmd'
        elif line.startswith('## '):
            section = None
        if not section or not line.startswith('| ') or line.startswith('|---'):
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if section == 'cvar' and len(cells) >= 4:
            for part in cells[0].split(','):
                part = part.strip()
                m = re.match(r'^(\w*?)(\d+) \.\. (\w*?)(\d+)$', part)
                if m:
                    for i in range(int(m.group(2)), int(m.group(4)) + 1):
                        cv['%s%d' % (m.group(1), i)] = cells[3]
                else:
                    cv[part] = cells[3]
        elif section == 'cmd' and len(cells) >= 2:
            cm[cells[0]] = cells[1]
    return cv, cm


# owner packages for names that the I1a engine core does not register
def cvar_owner(name, regby):
    if regby.startswith('cfg') or regby.startswith('(none'):
        return 'cfg (created by a shipped .cfg file)'
    if regby == 'renderer':
        return 'renderer internals (I4a)'
    if regby == 'sound':
        return 'sound module'
    if regby == 'game':
        return 'game module (G*)'
    return None


def cmd_owner(name, regby):
    for key, owner in (('menus', 'menus (I6m)'), ('screen', 'HUD / screen (I6h)'),
                       ('effects', 'client effects (I5)'), ('force feedback', 'force feedback (optional)'),
                       ('GameSpy chat', 'GameSpy chat (optional, masters gone)'),
                       ('loaded module', 'renderer / sound module'), ('console', 'console (I6h)'),
                       ('input', 'input (I6h)'), ('view', 'view (I6h)'), ('video', 'video (I4a/I6h)')):
        if key in regby:
            return owner
    return None


def main():
    oracle, om, spec, out = sys.argv[1:5]
    ocv, ocm, onv, onc = parse_log(oracle)
    mcv, mcm, mnv, mnc = parse_log(om)
    scv, scm = parse_spec(spec)

    lines = []
    w = lines.append
    w('# I1a: cvarlist / cmdlist of OpenMerc compared with the original 1.07f client')
    w('')
    w('Generated by `tools/diff_cvarcmd.py`. Oracle: black-box console log of the original client after a plain')
    w('start (`%s`); OpenMerc: `%s`.' % (oracle.replace('\\', '/').split('/')[-1], om.replace('\\', '/').split('/')[-1]))
    w('')
    w('| | original | OpenMerc |')
    w('|---|---|---|')
    w('| `cvarlist` count | %d | %d |' % (onv, mnv))
    w('| `cmdlist` count | %d | %d |' % (onc, mnc))
    w('')

    # cvars present in both
    same, flagdiff, valdiff = 0, [], []
    for n in ocv:
        if n in mcv:
            if ocv[n][0] != mcv[n][0]:
                flagdiff.append(n)
            elif ocv[n][1] != mcv[n][1]:
                valdiff.append(n)
            else:
                same += 1
    missing = [n for n in ocv if n not in mcv]
    extra = [n for n in mcv if n not in ocv]

    w('## Cvars')
    w('')
    w('- listed by both with identical flags and value: %d' % same)
    w('- listed by both, flags differ: %d' % len(flagdiff))
    w('- listed by both, same flags, value differs: %d' % len(valdiff))
    w('- only in the original: %d' % len(missing))
    w('- only in OpenMerc: %d' % len(extra))
    w('')

    groups = {}
    unexpected = []
    for n in missing:
        owner = cvar_owner(n, scv.get(n, ''))
        if owner:
            groups.setdefault(owner, []).append(n)
        else:
            unexpected.append(n)

    w('### Only in the original, by owner (expected-missing)')
    w('')
    for owner in sorted(groups):
        w('- **%s** (%d): %s' % (owner, len(groups[owner]), ', '.join('`%s`' % x for x in groups[owner])))
    w('')
    w('### Only in the original, registered by the engine (to do)')
    w('')
    w(', '.join('`%s`' % x for x in unexpected) if unexpected else 'none')
    w('')
    w('### Flags differ (original / OpenMerc)')
    w('')
    if flagdiff:
        w('Flag columns as printed by `cvarlist` (`%s`), "." = column empty.' % FLAGCOLS)
        w('')
        w('| cvar | original | OpenMerc | registered by (SPEC-302) |')
        w('|---|---|---|---|')
        for n in flagdiff:
            w('| `%s` | `%s` "%s" | `%s` "%s" | %s |' % (n, ocv[n][0].replace(' ', '.'), ocv[n][1],
                                                     mcv[n][0].replace(' ', '.'), mcv[n][1], scv.get(n, '?')))
    else:
        w('none')
    w('')
    w('### Same flags, value differs (original / OpenMerc)')
    w('')
    if valdiff:
        w('| cvar | original | OpenMerc |')
        w('|---|---|---|')
        for n in valdiff:
            w('| `%s` | "%s" | "%s" |' % (n, ocv[n][1], mcv[n][1]))
    else:
        w('none')
    w('')
    w('### Only in OpenMerc')
    w('')
    w(', '.join('`%s`' % x for x in extra) if extra else 'none')
    w('')

    # commands
    oset, mset = set(ocm), set(mcm)
    cmissing = [c for c in ocm if c not in mset]
    cextra = [c for c in mcm if c not in oset]
    w('## Commands')
    w('')
    w('- in both: %d' % len(oset & mset))
    w('- only in the original: %d' % len(cmissing))
    w('- only in OpenMerc: %d' % len(cextra))
    w('')
    cgroups, cunexp = {}, []
    for c in cmissing:
        owner = cmd_owner(c, scm.get(c, ''))
        if owner:
            cgroups.setdefault(owner, []).append(c)
        else:
            cunexp.append(c)
    w('### Only in the original, by owner (expected-missing)')
    w('')
    for owner in sorted(cgroups):
        w('- **%s** (%d): %s' % (owner, len(cgroups[owner]), ', '.join('`%s`' % x for x in cgroups[owner])))
    w('')
    w('### Only in the original, engine (to do)')
    w('')
    w(', '.join('`%s` (%s)' % (x, scm.get(x, '?')) for x in cunexp) if cunexp else 'none')
    w('')
    w('### Only in OpenMerc')
    w('')
    w(', '.join('`%s`' % x for x in cextra) if cextra else 'none')
    w('')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('cvars: %d/%d, same %d, flagdiff %d, valdiff %d, missing %d (unexpected %d), extra %d' %
          (onv, mnv, same, len(flagdiff), len(valdiff), len(missing), len(unexpected), len(extra)))
    print('cmds: %d/%d, missing %d (unexpected %d), extra %d' % (onc, mnc, len(cmissing), len(cunexp), len(cextra)))


if __name__ == '__main__':
    main()
