"""Generate script_ai_table.inc (the AI command table of SPEC-750 section 12.7) from the spec text.

usage: gen_ai_table.py <SPEC-750-script-vm.md> <out.inc>
"""
import re
import sys

ROW = re.compile(r"^\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|")


def main(spec, out):
    text = open(spec, encoding="utf-8").read()
    start = text.index("### 12.7 AI command table")
    end = text.index("\n## ", start)
    rows = []
    for line in text[start:end].splitlines():
        m = ROW.match(line)
        if not m:
            continue
        cid, kind, speed, anim = int(m.group(1)), int(m.group(2)), m.group(3), m.group(4)
        speed = 0 if speed in ("—", "-", "") else int(speed)
        anim = None if anim.startswith("—") else anim.strip("`")
        rows.append((cid, kind, speed, anim))
    ids = [r[0] for r in rows]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate command ids")
    # SPEC-AMEND-003 3: the table row for id 3 is an error of SPEC-750 (id 3 has no entry: default behaviour)
    rows = [r for r in rows if r[0] != 3]
    if len(rows) != 341:
        raise SystemExit("expected 341 table entries, found %d" % len(rows))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* SPDX-License-Identifier: GPL-2.0-or-later */\n")
        f.write("/* Implements: SPEC-750 section 12.7. Generated by tools/gen_ai_table.py - do not edit. */\n")
        f.write("/* id, action kind, default speed, animation */\n")
        for cid, kind, speed, anim in sorted(rows):
            a = '"%s"' % anim if anim else "nullptr"
            f.write("{%d, %d, %d, %s},\n" % (cid, kind, speed, a))
    print("%d entries -> %s" % (len(rows), out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
