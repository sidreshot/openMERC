# Implements: SPEC-010, SPEC-011, SPEC-003 (test scaffolding only)
# Generates stub_bases.h: classes implementing every pure virtual method of ghoul::IGhoulInst, ghoul::IGhoulObject
# and PlayerInventory with neutral bodies, so the unit-test mocks only override what they need.
import os, re
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.abspath(os.path.join(here, '..', '..'))

def methods(path, cls):
    text = open(os.path.join(src, path), encoding='utf-8').read()
    m = re.search(r'class %s\s*\{(.*?)\n\};' % cls, text, re.S)
    body = re.sub(r'//[^\n]*', '', m.group(1))
    out = []
    for decl in re.findall(r'virtual\s+([^;]*?)\)\s*=\s*0\s*;', body, re.S):
        decl = ' '.join(decl.split()) + ')'
        mm = re.match(r'(.*?)\b(\w+)\s*\((.*)\)$', decl)
        ret, name, args = mm.group(1).strip(), mm.group(2), mm.group(3)
        out.append((ret, name, args))
    return out

def emit(base, ns, cls, ms):
    o = ['class %s : public %s%s {' % (base, ns, cls), 'public:']
    for ret, name, args in ms:
        if ret == 'void':
            b = '{}'
        elif ret.endswith('*'):
            b = '{ return 0; }'
        elif ret == 'bool':
            b = '{ return false; }'
        else:
            b = '{ return 0; }'
        o.append('\t%s %s(%s) override %s' % (ret, name, args, b))
    o.append('};')
    return '\n'.join(o)

ms_inst = methods('ghoul.h', 'IGhoulInst')
ms_obj = methods('ghoul.h', 'IGhoulObject')
ms_inv = methods('player_api.h', 'PlayerInventory')
ms_sys = methods('ghoul.h', 'IGhoulSystem')
text = ['// SPDX-License-Identifier: GPL-2.0-or-later', '// Generated by gen_stubbases.py (test scaffolding).',
        '// Implements: SPEC-010, SPEC-011, SPEC-003 (neutral stubs)', '#pragma once',
        '#pragma warning(disable : 4100)',
        'namespace ghoul {', emit('StubInst', '', 'IGhoulInst', ms_inst), emit('StubObject', '', 'IGhoulObject', ms_obj), emit('StubSystem', '', 'IGhoulSystem', ms_sys),
        '}', emit('StubInventory', '', 'PlayerInventory', ms_inv), '']
open(os.path.join(here, 'stub_bases.h'), 'w', newline='\n').write('\n'.join(text))
print(len(ms_inst), len(ms_obj), len(ms_inv))
