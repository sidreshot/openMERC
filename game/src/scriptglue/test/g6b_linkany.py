# OpenMerc G6b - test-only link of gamex86.dll while sibling packages are mid-edit (never shipped).
# Builds the full game tree with ninja -k 0, takes every object that is up to date with its source, links them with
# om_script; symbols left unresolved by the sources that did not compile are given no-op fallbacks (MSVC x86
# /alternatename to a stub returning 0 / 0.0f / a zeroed data block). The result behaves like the real module except
# that the missing package code does nothing.
# Implements: (test scaffolding for SPEC-750/751 black-box runs)
#
# usage: g6b_linkany.py [--build DIR] [--out DIR] [--exclude PKG ...]     default build-G6b-x86, output <build>\any\gamex86.dll

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
VCVARS = r"C:\BuildTools\VC\Auxiliary\Build\vcvarsall.bat"
LIBS = "kernel32.lib user32.lib gdi32.lib winspool.lib shell32.lib ole32.lib oleaut32.lib uuid.lib comdlg32.lib advapi32.lib"


def vc(cmd, cwd):
    full = 'call "%s" x86 >nul 2>&1 && %s' % (VCVARS, cmd)
    r = subprocess.run('cmd /s /c "%s"' % full, cwd=cwd, capture_output=True, text=True, encoding="cp866", errors="replace")
    return r.returncode, r.stdout + r.stderr


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default=str(REPO / "build-G6b-x86"))
    ap.add_argument("--out")
    ap.add_argument("--exclude", action="append", default=[], help="package directory to leave out (e.g. roster)")
    a = ap.parse_args(argv)
    build = Path(a.build)
    out = Path(a.out) if a.out else build / "any"
    out.mkdir(parents=True, exist_ok=True)
    _, log = vc("cmake --build \"%s\" -j %d -- -k 0" % (build, os.cpu_count() or 4), str(REPO))
    failed = sorted(set(re.findall(r"FAILED: \[code=\d+\] (\S+\.obj)", log)))
    objdir = build / "CMakeFiles" / "gamex86.dir"
    objs, skipped = [], []
    for obj in objdir.rglob("*.obj"):
        rel = obj.relative_to(objdir).as_posix()[:-4]          # src/x/y.cpp
        src = REPO / "game" / rel
        if any(rel.startswith("src/%s/" % x) for x in a.exclude) or not src.exists() or                 obj.stat().st_mtime < src.stat().st_mtime or ("CMakeFiles/gamex86.dir/" + rel + ".obj") in failed:
            skipped.append(rel)
            continue
        objs.append(str(obj))
    rsp = out / "objs.rsp"
    rsp.write_text("\n".join('"%s"' % o for o in objs), encoding="utf-8")
    base = ('link /nologo /DLL /machine:X86 /INCREMENTAL:NO /OPT:REF /MAP /DEF:"%s" /OUT:"%s" @"%s" "%s" %s'
            % (REPO / "game" / "gamex86.def", out / "gamex86.dll", rsp, build / "src" / "script" / "om_script.lib",
               LIBS))
    rc, log = vc(base, str(out))
    stubs = {}
    for line in log.splitlines():
        if "LNK2019" not in line and "LNK2001" not in line:
            continue
        m = re.search(r'"([^"]+)" \((\?[^)\s]+|_[^)\s]+)\)', line)  # the first symbol is the unresolved one
        if m:
            stubs[m.group(2)] = m.group(1)
    if rc != 0 and stubs:
        lines = ["// generated by g6b_linkany.py - no-op fallbacks for unresolved symbols (test only)",
                 'extern "C" int g6b_stub_i(void) { return 0; }',
                 'extern "C" float g6b_stub_f(void) { return 0.0f; }',
                 'extern "C" double g6b_stub_d(void) { return 0.0; }',
                 'extern "C" char g6b_stub_data[65536];']
        for sym, undec in sorted(stubs.items()):
            if "@@3" in sym:
                tgt = "_g6b_stub_data"
            elif re.match(r"(static )?(public: |private: |protected: )?(virtual )?float ", undec):
                tgt = "_g6b_stub_f"
            elif re.match(r"(static )?(public: |private: |protected: )?(virtual )?double ", undec):
                tgt = "_g6b_stub_d"
            else:
                tgt = "_g6b_stub_i"
            if "__thiscall" in undec:
                print("warning: thiscall stub (stack not cleaned):", undec)
            lines.append('#pragma comment(linker, "/alternatename:%s=%s")' % (sym, tgt))
        (out / "g6b_stubs.cpp").write_text("\n".join(lines) + "\n", encoding="utf-8")
        rc2, log2 = vc('cl /nologo /c /O2 /MT g6b_stubs.cpp', str(out))
        if rc2:
            print(log2)
            return 1
        rsp.write_text(rsp.read_text(encoding="utf-8") + '\n"%s"' % (out / "g6b_stubs.obj"), encoding="utf-8")
        rc, log = vc(base, str(out))
    print("compile failures:", ", ".join(f.split("gamex86.dir/")[-1] for f in failed) or "none")
    print("objects linked: %d, skipped (failed or stale): %d %s" % (len(objs), len(skipped), skipped[:12]))
    print("stubbed symbols: %d" % len(stubs))
    for sym, undec in sorted(stubs.items(), key=lambda x: x[1])[:80]:
        print("   ", undec[:150])
    if rc:
        print(log[-3000:])
        return 1
    print("linked", out / "gamex86.dll")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
